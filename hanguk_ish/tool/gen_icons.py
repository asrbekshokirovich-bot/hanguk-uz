# Generates hanguk_ish/lib/design/hi_icons.g.dart from the prototype's inline
# Lucide SVGs, so the path data is copied by machine, never retyped.
import re, sys, collections, html
src = open(sys.argv[1], encoding='utf-8').read()
out = sys.argv[2]
NAMES = {
 0:'check',1:'smartphone',2:'send',3:'chevronLeft',4:'camera',5:'plus',6:'graduationCap',7:'chevronDown',
 8:'mapPin',9:'list',10:'map',11:'bell',12:'slidersHorizontal',13:'moon',14:'badgeCheck',15:'coffee',
 16:'clock',17:'utensils',18:'shoppingBag',19:'briefcase',20:'calendarCheck',21:'wallet',22:'user',
 23:'mapPinOff',24:'wifiOff',25:'refreshCw',27:'locateFixed',28:'image',29:'calendar',30:'star',
 31:'clipboardList',32:'shirt',34:'info',35:'triangleAlert',36:'x',37:'scanLine',38:'timer',39:'navigation',
 40:'messageCircle',42:'flashlight',44:'chevronRight',45:'languages',46:'globe',47:'flag',48:'circleHelp',
 49:'userX',50:'house',51:'users',52:'chartColumn',53:'minus',54:'pencil',55:'printer',56:'search',57:'download',
}
tpls = re.findall(r'<template id="t-([^"]+)">([\s\S]*?)</template>', src)
icons = collections.OrderedDict()
for name, body in tpls:
    for m in re.finditer(r'<svg([^>]*)>(.*?)</svg>', body, flags=re.S):
        attrs, inner = m.group(1), re.sub(r'\s+', ' ', m.group(2).strip())
        vb = re.search(r'viewBox="([^"]+)"', attrs)
        icons.setdefault(((vb.group(1) if vb else ''), inner), set()).add(name)
def num(s):
    v = float(s); return repr(v) if not v.is_integer() else f'{int(v)}'
def shapes(inner):
    res = []
    for el in re.finditer(r'<(path|rect|circle|line|polyline|polygon)\b([^>]*)/?>', inner):
        tag, a = el.group(1), el.group(2)
        g = lambda k, d=None: (re.search(rf'\b{k}="([^"]*)"', a).group(1) if re.search(rf'\b{k}="([^"]*)"', a) else d)
        if tag == 'path':
            d = html.unescape(g('d')).replace("'", "\\'")
            res.append(f"HiPathShape('{d}')")
        elif tag == 'rect':
            rx = g('rx', '0'); ry = g('ry', rx)
            res.append(f"HiRectShape({num(g('x','0'))}, {num(g('y','0'))}, {num(g('width'))}, {num(g('height'))}, {num(rx)}, {num(ry)})")
        elif tag == 'circle':
            res.append(f"HiCircleShape({num(g('cx'))}, {num(g('cy'))}, {num(g('r'))})")
        elif tag == 'line':
            res.append(f"HiLineShape({num(g('x1'))}, {num(g('y1'))}, {num(g('x2'))}, {num(g('y2'))})")
        else:
            pts = [num(p) for p in re.split(r'[\s,]+', g('points').strip())]
            cls = 'HiPolylineShape' if tag == 'polyline' else 'HiPolygonShape'
            res.append(f"{cls}([{', '.join(pts)}])")
    return res
lines = ["// GENERATED by tool/gen_icons.py from the Claude Design prototype",
         "// (2026-11-10). Do not edit by hand: re-run the script instead.",
         "// Icons are Lucide (ISC licence), drawn on a 24×24 grid.",
         "", "part of 'icons.dart';", "", "abstract final class HiIcons {"]
seen = set()
for i, ((vb, inner), screens) in enumerate(icons.items()):
    if i not in NAMES: continue
    if vb != '0 0 24 24': sys.exit(f'icon {i} has viewBox {vb}')
    n = NAMES[i]; assert n not in seen; seen.add(n)
    sh = shapes(inner)
    if not sh: sys.exit(f'icon {i} produced no shapes')
    used = ', '.join(sorted(screens)[:4]) + (' …' if len(screens) > 4 else '')
    lines.append(f"  /// Lucide `{re.sub(r'([A-Z])', lambda m: '-' + m.group(1).lower(), n)}` — {used}")
    lines.append(f"  static const {n} = HiIconData([")
    for s in sh: lines.append(f"    {s},")
    lines.append("  ]);")
    lines.append("")
lines[-1:] = ["}", ""]
open(out, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote', len(seen), 'icons')
