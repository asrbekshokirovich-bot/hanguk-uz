#!/usr/bin/env node
/**
 * Generate a frontend `.env.local` that points the app at the LOCAL Supabase
 * stack. Reads the real keys from a running `supabase` stack (so nothing is
 * hardcoded or guessed) and writes VITE_* vars that Vite loads with higher
 * priority than the committed `.env`.
 *
 * Usage:
 *   1. supabase start        (or: npm run db:start)
 *   2. node scripts/gen-local-env.mjs   (or: npm run env:local)
 *   3. npm run dev
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envLocalPath = resolve(root, ".env.local");

function readStatusEnv() {
  // Prefer the local node_modules binary, fall back to a globally-installed one.
  const candidates = [
    resolve(root, "node_modules/.bin/supabase"),
    "supabase",
  ];
  let lastErr;
  for (const bin of candidates) {
    try {
      return execFileSync(bin, ["status", "-o", "env"], {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
      });
    } catch (err) {
      lastErr = err;
    }
  }
  throw lastErr;
}

function parseEnv(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?(.*?)"?\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

let raw;
try {
  raw = readStatusEnv();
} catch (err) {
  console.error(
    "\n✗ Could not read `supabase status`. Is the local stack running?\n" +
      "  Start it first:  npm run db:start   (or: npx supabase start)\n"
  );
  console.error(String(err.stderr || err.message || err).trim());
  process.exit(1);
}

const status = parseEnv(raw);
const apiUrl = status.API_URL || status.SUPABASE_URL;
const anonKey = status.ANON_KEY || status.SUPABASE_ANON_KEY;

if (!apiUrl || !anonKey) {
  console.error(
    "\n✗ `supabase status` did not report API_URL / ANON_KEY. Raw output:\n"
  );
  console.error(raw);
  process.exit(1);
}

const lines = [
  "# Auto-generated by scripts/gen-local-env.mjs — points the app at the LOCAL",
  "# Supabase stack. Vite loads .env.local ahead of the committed .env, so this",
  "# transparently overrides the cloud values for local development.",
  "# Re-run `npm run env:local` after `supabase start` if the keys change.",
  "",
  `VITE_SUPABASE_URL="${apiUrl}"`,
  `VITE_SUPABASE_PUBLISHABLE_KEY="${anonKey}"`,
  `VITE_SUPABASE_PROJECT_ID="local"`,
  "",
];

writeFileSync(envLocalPath, lines.join("\n"), "utf8");
console.log(
  `✓ Wrote ${existsSync(envLocalPath) ? "" : ""}${envLocalPath}\n` +
    `  VITE_SUPABASE_URL=${apiUrl}\n` +
    `  VITE_SUPABASE_PUBLISHABLE_KEY=${anonKey.slice(0, 24)}…\n\n` +
    "  Now run:  npm run dev\n"
);
